import { useState } from 'react';
import { useNavigate } from 'react-router';
import { useAppProfile } from '../hooks/useAppProfile';
import { getAccounts } from '../data/accounts';
import { getTransactions } from '../data/transactions';
import { getGoals } from '../data/goals';
import { savePreview } from '../utils/paymentPreview';
import { Button } from '../components/ui/button';
import { BalanceHero } from '../components/zapad/BalanceHero';
import { AccountsStrip } from '../components/zapad/AccountsStrip';
import { PaymentCard } from '../components/zapad/PaymentCard';
import { Transactions } from '../components/zapad/Transactions';
import { TransactionDetailsSheet } from '../components/zapad/TransactionDetailsSheet';
import { CashFlowAnalytics } from '../components/zapad/CashFlowAnalytics';
import { ExpenseAnalytics } from '../components/zapad/ExpenseAnalytics';
import { SavingsGoals } from '../components/zapad/SavingsGoals';
import { GoalDialog } from '../components/zapad/GoalDialog';
import { RightPanel,AlertsCard,CardWidget } from '../components/zapad/RightPanel';
import { QuickActions } from '../components/zapad/QuickActions';
import { DashboardPaymentsCta } from '../components/zapad/DashboardPaymentsCta';
import { TransferModal } from '../components/zapad/TransferModal';
import { ReceiveSheet } from '../components/zapad/ReceiveSheet';
import { ExchangeModal } from '../components/zapad/ExchangeModal';
import { ProductPreviewDialog } from '../components/zapad/ProductPreviewDialog';
import { PreviewHistory } from '../components/zapad/PreviewHistory';
import { LanguageSwitcher } from '../components/zapad/LanguageSwitcher';
import { SidebarContent } from '../components/zapad/Sidebar';
import { TopBar } from '../components/zapad/TopBar';
import type { SpecimenProps } from './types';

export function Bank({sample,state}:SpecimenProps) {
  const {profile,profileSlug,isBusiness,setProfileSlug}=useAppProfile();
  const navigate=useNavigate();
  const accounts=getAccounts(profile.kind);
  const [accountId,setAccountId]=useState(accounts[0].id);
  const [open,setOpen]=useState(true);
  useState(()=>{
    if(sample==='preview-history'&&state!=='empty')savePreview({id:'gallery-preview',kind:profile.kind,createdAt:'2026-05-20T12:00:00Z',title:'Sample payment',sourceId:accounts[0].id,source:accounts[0].name,recipient:'Sample supplier',iban:'ME25505000012345678951',amount:250,currency:'EUR',fee:1,total:251,received:250,targetCurrency:'EUR',note:'Gallery example',status:state==='approval'&&isBusiness?'Awaiting approval':'Preview saved',initiator:'Sample initiator',events:['Created locally. No payment submitted.']});
    return true;
  });
  const account=accounts.find(item=>item.id===accountId)??accounts[0];
  const close=()=>setOpen(false);
  const reopen=<Button variant="outline" onClick={()=>setOpen(true)}>Open example</Button>;
  if(sample==='language')return <LanguageSwitcher compact={state==='compact'}/>;
  if(sample==='bank-navigation')return state==='topbar'?<TopBar profile={profile} profileSlug={profileSlug} onProfileChange={setProfileSlug} onMenuClick={()=>navigate(`/${profileSlug}/menu`)}/>:<SidebarContent active="dashboard" onChange={id=>navigate(`/${profileSlug}/${id==='dashboard'?'':id}`)} profileSlug={profileSlug} isBusiness={isBusiness}/>;
  if(sample==='balance')return state==='accounts'?<AccountsStrip accounts={accounts} profileSlug={profileSlug}/>:<BalanceHero isBusiness={isBusiness} primaryAccount={account} profileKind={profile.kind} accounts={accounts} onAccountChange={setAccountId}/>;
  if(sample==='payment-card')return <PaymentCard name={`${isBusiness?'Business':'Personal'} ${state==='virtual'?'Virtual':'Visa'}`} last4="4242" expiry="12/28" holder={profile.name} frozen={state==='frozen'} isPrivate={state==='private'}/>;
  if(sample==='transactions')return state==='details'?<>{reopen}<TransactionDetailsSheet transaction={getTransactions(profile.kind)[0]} open={open} onOpenChange={setOpen} isBusiness={isBusiness}/></>:<Transactions profileKind={profile.kind} account={state==='empty'?{...account,id:'gallery-empty'}:undefined} compact={state==='compact'} viewAllHref={`/${profileSlug}/transactions`}/>;
  if(sample==='analytics'&&state==='cashflow')return <div data-dashboard-material="soft"><CashFlowAnalytics key={profile.kind} profileKind={profile.kind}/></div>;
  if(sample==='analytics')return <ExpenseAnalytics business={isBusiness} compact={state==='compact'} transactionsHref={`/${profileSlug}/transactions`}/>;
  if(sample==='savings-goals')return state==='create'||state==='details'?<>{reopen}{open&&<GoalDialog kind={profile.kind} goalId={state==='details'?getGoals(profile.kind)[0]?.id:undefined} onClose={close}/>}</>:<SavingsGoals profileKind={profile.kind} profileSlug={profileSlug} compact={state==='compact'}/>;
  const panelProps={business:isBusiness,profileSlug,profileKind:profile.kind,compact:state==='compact'};
  if(sample==='right-panel')return state==='alerts'?<AlertsCard {...panelProps}/>:state==='card'?<CardWidget {...panelProps}/>:<RightPanel {...panelProps}/>;
  if(sample==='quick-actions')return state==='dashboard'?<DashboardPaymentsCta profileSlug={profileSlug} isBusiness={isBusiness}/>:<QuickActions/>;
  if(sample==='transfer')return <>{reopen}<TransferModal open={open} onOpenChange={setOpen} type={state==='transfer'?'transfer':state==='bills'?'pay':'send'}/></>;
  if(sample==='receive')return <>{reopen}<ReceiveSheet open={open} onClose={close} profileKind={profile.kind}/></>;
  if(sample==='exchange')return <>{reopen}<ExchangeModal open={open} onOpenChange={setOpen}/></>;
  if(sample==='product-preview')return <>{reopen}<ProductPreviewDialog open={open} onClose={close} title="Savings preview" options={[{name:'Flexible savings'}]} initialAmount={state==='filled'?'250':''} savings={state==='withdraw'?'Flexible savings':undefined} direction={state==='withdraw'?'withdraw':'deposit'} explanation="Sample calculation. No funds are moved."/></>;
  if(sample==='preview-history')return <PreviewHistory kind={profile.kind}/>;
  return null;
}
